export const ST_SHAPE_TYPE_SET = new Set<string>(ST_SHAPE_TYPES);

export const isStShapeType = (value: string): value is StShapeType => ST_SHAPE_TYPE_SET.has(value);

/** Harvey-ball fill fraction → pie adj (OOXML guide, 0–21600000 = full circle). */
export const harveyBallPieAdj = (value: 0 | 0.25 | 0.5 | 0.75 | 1): number => {
  // Empty / full use ellipse; pie adj for partial fills: remaining unfilled arc.
  const filled = value;
  const unfilledFraction = 1 - filled;
  return Math.round(unfilledFraction * 21_600_000);
};
