#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packagePath = resolve(root, 'packages/deckuse/package.json');
const outputPath = resolve(root, 'packages/deckuse/src/version.ts');
const { version } = JSON.parse(await readFile(packagePath, 'utf8'));

if (typeof version !== 'string') {
  throw new TypeError(`Expected a string version in ${packagePath}`);
}

await writeFile(
  outputPath,
  `// Generated by scripts/generate-cli-version.mjs. Do not edit.\nexport const version = '${version}';\n`,
);
